def migrate(db):
    db.execute("CREATE TABLE IF NOT EXISTS schema_version (id INTEGER PRIMARY KEY CHECK (id = 1), version INTEGER NOT NULL)")
    row = db.one("SELECT version FROM schema_version WHERE id=1")
    current = row["version"] if row else 1
    for version, stmts in _migrations(_id(db.dialect)):
        if version <= current:
            continue
        with db.tx():
            for st in stmts:
                db.execute(st)
            db.execute("DELETE FROM schema_version")
            db.execute("INSERT INTO schema_version (id, version) VALUES (1, ?)", (version,))
        current = version


def schema_version(db) -> int:
    row = db.one("SELECT version FROM schema_version WHERE id=1")
    return row["version"] if row else 1
